// Backfills the crossing pages' HEAD and CHROME copy — the parts increment 2
// deliberately left behind: the hero intro paragraph, the meta description,
// the eyebrow, the difficulty chip label, the Key Facts triples (with their
// notes), the benchmarks/prose split of the Preparation section, and the
// readiness/CTA blurbs. All bespoke, all lifted verbatim by the extractor,
// none derivable from the columns increment 2 filled.
//
// Writes BOTH the migration file (the reviewable record) and, with --apply,
// the update itself from that same source — one source, so the file and the
// database can never disagree.
//
//   node scripts/backfill-crossing-heads.mjs <extractor.json>            # write the .sql only
//   node scripts/backfill-crossing-heads.mjs <extractor.json> --apply    # ...and apply it
import { readFileSync, writeFileSync } from 'node:fs';
import { createClient } from '@supabase/supabase-js';

const SKIP = new Set(['english-channel']); // stays a hand-written page — see the handover, §5
const OUT = 'sql/2026-08-14_crossing-page-heads.sql';

const src = process.argv[2];
if (!src || src.startsWith('--')) { console.error('usage: node scripts/backfill-crossing-heads.mjs <extractor.json> [--apply]'); process.exit(1); }
const data = JSON.parse(readFileSync(src, 'utf8')).filter(r => !SKIP.has(r.slug) && !r.missing);

const q = (s) => s === null || s === undefined || s === '' ? 'NULL' : `'${String(s).replace(/'/g, "''")}'`;
const jq = (o) => `'${JSON.stringify(o).replace(/'/g, "''")}'::jsonb`;

// Shape each row once, so the SQL file and the --apply path write the
// identical values.
function shape(r) {
  return {
    intro: r.intro || null,
    seo_description: r.seoDescription || null,
    key_facts: Object.entries(r.keyFacts || {}).map(([label, f]) => ({ label, val: f.val, note: f.note || '' })),
    prep_benchmarks: r.prepBenchmarks || [],
    // preparation becomes PROSE-ONLY: the benchmarks now live in their own
    // column, and a flat mix of the two cannot be rendered back into the
    // page's checklist-box + prose-card layout.
    preparation: r.prepProse || [],
    page_copy: {
      eyebrow: r.eyebrow, difficulty_label: r.difficultyLabel,
      challenge_title: r.challengeTitle, benchmarks_label: r.benchmarksLabel,
      readiness_title: r.readinessTitle, readiness_blurb: r.readinessBlurb,
      cta_title: r.ctaTitle, cta_blurb: r.ctaBlurb,
    },
    // faqs re-set from the page for north-channel only: the page was
    // corrected on 2026-08-14 (ICA does not ratify crossings — the ILDSA
    // does) and the jsonb backfilled on the 14th still carries the old
    // false claim. Other crossings' faqs are already correct and untouched.
    faqs: r.slug === 'north-channel' ? r.faqs : undefined,
  };
}

const statements = [];
for (const r of data) {
  const s = shape(r);
  const set = {
    intro: q(s.intro), seo_description: q(s.seo_description),
    key_facts: jq(s.key_facts), prep_benchmarks: jq(s.prep_benchmarks),
    preparation: jq(s.preparation), page_copy: jq(s.page_copy),
    ...(s.faqs ? { faqs: jq(s.faqs) } : {}),
  };
  statements.push(`UPDATE public.crossings SET\n${Object.entries(set).map(([k, v]) => `  ${k} = ${v}`).join(',\n')},\n  updated_at = now()\nWHERE slug = '${r.slug}';`);
}

const sql = `-- ================================================================
-- SwimLoading — Migration Template
-- ================================================================

-- ⚠️  SAFETY CHECK — runs first, aborts everything if wrong project
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM _project_identity
    WHERE key = 'project_name' AND value = 'swimloading'
  ) THEN
    RAISE EXCEPTION 'WRONG PROJECT — MIGRATION ABORTED (expected swimloading / szgkzuswelntnevobnoh)'
    USING HINT = 'Check the project ref in your Supabase dashboard URL';
  END IF;
  RAISE NOTICE '✅ Project identity confirmed: swimloading (szgkzuswelntnevobnoh)';
END $$;

-- ================================================================
-- Migration: 2026-08-14_crossing-page-heads.sql
-- Generated by scripts/backfill-crossing-heads.mjs — edit the pages
-- and regenerate rather than hand-editing this file.
-- ================================================================

-- Purpose:
--   SEO increment 3, step 1: store the crossing pages' bespoke head/hero/
--   chrome copy (intro, meta description, key-fact triples, benchmarks/
--   prose split, page micro-copy) so the shared template can reproduce the
--   live pages without loss. Also corrects the north-channel faqs jsonb:
--   ratification sits with the ILDSA, not "the Infinity Channel
--   Association" (Dave confirmed 2026-08-14; Infinity Channel Swimming is
--   a piloting/support operation).

-- Requested by:
--   Dave (SEO acquisition layer, increment 3)

-- ----------------------------------------------------------------
-- PRE-CHECKS — run on the READ-ONLY connection BEFORE applying.
-- ----------------------------------------------------------------
-- Expect 10 (all content-bearing crossings, english-channel excluded):
-- SELECT count(*) FROM public.crossings WHERE slug IN (${data.map(r => `'${r.slug}'`).join(', ')});
-- Expect 1 (the stale ICA claim still present before applying):
-- SELECT count(*) FROM public.crossings WHERE slug = 'north-channel' AND faqs::text LIKE '%Infinity Channel Association%';

-- ----------------------------------------------------------------
-- BACKUP — required: this UPDATEs existing preparation + faqs values.
-- ----------------------------------------------------------------
CREATE TABLE IF NOT EXISTS _bak_20260814_crossings AS SELECT * FROM public.crossings;

-- ----------------------------------------------------------------
-- MIGRATION — applied only after Dave types "apply".
-- ----------------------------------------------------------------
BEGIN;

ALTER TABLE public.crossings
  ADD COLUMN IF NOT EXISTS intro text,
  ADD COLUMN IF NOT EXISTS seo_description text,
  ADD COLUMN IF NOT EXISTS key_facts jsonb,
  ADD COLUMN IF NOT EXISTS prep_benchmarks jsonb,
  ADD COLUMN IF NOT EXISTS page_copy jsonb;

COMMENT ON COLUMN public.crossings.intro           IS 'Hero intro paragraph, verbatim from the page — the sentence doing the most SEO work';
COMMENT ON COLUMN public.crossings.seo_description IS 'Meta description, verbatim from the page';
COMMENT ON COLUMN public.crossings.key_facts       IS '[{label, val, note}] — the Key Facts cards verbatim; scalar columns stay canonical for queries';
COMMENT ON COLUMN public.crossings.prep_benchmarks IS 'Training-benchmark checklist items; preparation column holds the prose paragraphs only';
COMMENT ON COLUMN public.crossings.page_copy       IS 'Bespoke page micro-copy: eyebrow, difficulty_label, section titles, readiness + CTA blurbs';

${statements.join('\n\n')}

COMMIT;

-- ----------------------------------------------------------------
-- ROLLBACK
-- ----------------------------------------------------------------
-- BEGIN;
-- UPDATE public.crossings c SET preparation = b.preparation, faqs = b.faqs
--   FROM _bak_20260814_crossings b WHERE b.slug = c.slug;
-- ALTER TABLE public.crossings
--   DROP COLUMN IF EXISTS intro, DROP COLUMN IF EXISTS seo_description,
--   DROP COLUMN IF EXISTS key_facts, DROP COLUMN IF EXISTS prep_benchmarks,
--   DROP COLUMN IF EXISTS page_copy;
-- COMMIT;

-- ----------------------------------------------------------------
-- VERIFY — read-only, after applying.
-- ----------------------------------------------------------------
-- Expect 10 rows, all columns filled:
-- SELECT count(*) FROM public.crossings WHERE intro IS NOT NULL AND seo_description IS NOT NULL
--   AND key_facts IS NOT NULL AND prep_benchmarks IS NOT NULL AND page_copy IS NOT NULL;
-- Expect 0 (false ICA claim gone):
-- SELECT count(*) FROM public.crossings WHERE faqs::text LIKE '%Infinity Channel Association%';
-- Expect 10 rows of 2 (preparation now prose-only):
-- SELECT slug, jsonb_array_length(preparation) FROM public.crossings WHERE prep_benchmarks IS NOT NULL;
`;

writeFileSync(OUT, sql);
console.log(`written ${OUT}`);
for (const r of data) {
  const s = shape(r);
  console.log(r.slug.padEnd(22), `facts:${s.key_facts.length} bench:${s.prep_benchmarks.length} prose:${s.preparation.length}`,
    `intro:${(s.intro || '').length}ch meta:${(s.seo_description || '').length}ch`, s.faqs ? 'faqs:CORRECTED' : '');
}

if (process.argv.includes('--apply')) {
  const db = createClient(process.env.SUPABASE_URL, process.env.SUPABASE_SERVICE_KEY, { auth: { persistSession: false } });
  for (const r of data) {
    const s = shape(r);
    const patch = {
      intro: s.intro, seo_description: s.seo_description, key_facts: s.key_facts,
      prep_benchmarks: s.prep_benchmarks, preparation: s.preparation, page_copy: s.page_copy,
      updated_at: new Date().toISOString(),
      ...(s.faqs ? { faqs: s.faqs } : {}),
    };
    const { error } = await db.from('crossings').update(patch).eq('slug', r.slug);
    if (error) { console.error(`FAILED ${r.slug}: ${error.message}`); process.exitCode = 1; continue; }
    const { count } = await db.from('crossings').select('slug', { count: 'exact', head: true })
      .eq('slug', r.slug).not('intro', 'is', null);
    console.log(count ? `applied  ${r.slug}` : `NO ROW   ${r.slug} — nothing was written`);
  }
}
