// Candidate matching for the global observation platform.
//
//   node scripts/match-observation-stations.mjs                 # dry run: report only
//   node scripts/match-observation-stations.mjs --sql out.sql   # also emit seed SQL
//   node scripts/match-observation-stations.mjs --write         # write via SUPABASE_SERVICE_KEY
//
// Pulls the real NDBC catalogue + latest observations (public, no key),
// reads the real spots table (anon key), and runs the same matching module
// the platform uses (api/_lib/observations/matching.js). Everything it
// produces is status='candidate' — approval happens in /admin, never here.

import { writeFileSync } from 'node:fs';
import {
  fetchStationCatalogue, fetchLatestObservations, fetchStationObservations,
} from '../api/_lib/observations/providers/ndbc.js';
import { generateCandidates, MATCH_CONFIG } from '../api/_lib/observations/matching.js';

const SUPABASE_URL = process.env.SUPABASE_URL || 'https://szgkzuswelntnevobnoh.supabase.co';
const ANON_KEY = process.env.SUPABASE_ANON_KEY ||
  'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZSIsInJlZiI6InN6Z2t6dXN3ZWxudG5ldm9ibm9oIiwicm9sZSI6ImFub24iLCJpYXQiOjE3NjgxODY1NTUsImV4cCI6MjA4Mzc2MjU1NX0.UfKqj2OZ-XeyzCy-MZYZqsDWjn_4EKrhgCFR8eIK2NA';

const args = process.argv.slice(2);
const sqlOutIdx = args.indexOf('--sql');
const sqlOut = sqlOutIdx !== -1 ? args[sqlOutIdx + 1] : null;
const doWrite = args.includes('--write');

async function anonGet(path) {
  const res = await fetch(`${SUPABASE_URL}/rest/v1/${path}`, {
    headers: { apikey: ANON_KEY, Authorization: `Bearer ${ANON_KEY}`, Accept: 'application/json' },
  });
  if (!res.ok) throw new Error(`REST ${res.status} for ${path}`);
  return res.json();
}

console.log('Fetching NDBC catalogue + latest observations…');
const [catalogue, latestObs, spots] = await Promise.all([
  fetchStationCatalogue(),
  fetchLatestObservations(),
  anonGet('spots?active=eq.true&select=id,name,water_type,latitude,longitude,country_code&order=name.asc'),
]);

const latestByStation = new Map();
for (const o of latestObs) {
  const prev = latestByStation.get(o.externalStationId);
  if (!prev || o.observedAt > prev.observedAt) latestByStation.set(o.externalStationId, o);
}

// Stations enter matching only if they currently report water temperature —
// temperature_available is learned from data, exactly as ingestion does it.
const stations = catalogue.map((s) => {
  const latest = latestByStation.get(s.externalId);
  return {
    externalId: s.externalId,
    name: s.name,
    latitude: s.latitude,
    longitude: s.longitude,
    stationType: s.stationType,
    sensorDepthM: s.sensorDepthM,
    waterBody: s.waterBody,
    metadata: s.metadata,
    temperatureAvailable: latest?.waterTemperatureC != null,
    active: true,
    lastObservationAt: latest?.observedAt || null,
    latestTempC: latest?.waterTemperatureC ?? null,
  };
});

const tempStations = stations.filter((s) => s.temperatureAvailable);
console.log(`Catalogue: ${catalogue.length} stations; ${tempStations.length} currently reporting water temperature.`);
console.log(`Spots: ${spots.length} active (${spots.filter((s) => MATCH_CONFIG.matchableWaterTypes.includes(s.water_type)).length} coastal OCEAN/LAGOON).`);

const { candidates, rejected } = generateCandidates(
  spots.map((s) => ({ ...s, latitude: Number(s.latitude), longitude: Number(s.longitude) })),
  tempStations,
);

console.log(`\n${candidates.length} candidate pairings within ${MATCH_CONFIG.maxDistanceKm} km:\n`);
for (const c of candidates) {
  console.log(
    `  ${String(c.suitabilityScore).padStart(5)}  ${c.spot.name.padEnd(30)} ← ${c.station.externalId.padEnd(6)} ` +
    `${(c.station.name || '').slice(0, 38).padEnd(38)} ${String(c.distanceKm).padStart(5)} km  ` +
    `${c.station.latestTempC != null ? c.station.latestTempC + '°C' : 'no temp'}`
  );
}
if (rejected.length) {
  console.log(`\n${rejected.length} pairings rejected structurally:`);
  for (const r of rejected.slice(0, 10)) {
    console.log(`  ${r.spot.name} ← ${r.station.externalId} (${r.distanceKm} km): ${r.reason}`);
  }
}

if (!candidates.length) {
  console.log('\nNo candidates — nothing to write.');
  process.exit(0);
}

// ── Persistence ──────────────────────────────────────────────────────────────
// Stations referenced by candidates, their latest observation, and the
// candidate links themselves. Idempotent: ON CONFLICT everywhere.

const wantedStations = [...new Map(candidates.map((c) => [c.station.externalId, c.station])).values()];

function q(v) {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
}

if (sqlOut) {
  const lines = [];
  lines.push('-- Seed generated by scripts/match-observation-stations.mjs');
  lines.push(`-- ${wantedStations.length} stations, ${candidates.length} candidate links. Idempotent.`);
  for (const st of wantedStations) {
    lines.push(
      `INSERT INTO observation_stations (provider_id, external_id, name, latitude, longitude, station_type, temperature_available, metadata, last_observation_at)\n` +
      `SELECT p.id, ${q(st.externalId)}, ${q(st.name)}, ${st.latitude}, ${st.longitude}, ${q(st.stationType)}, true, ${q(JSON.stringify(st.metadata || {}))}::jsonb, ${q(st.lastObservationAt ? st.lastObservationAt.toISOString() : null)}\n` +
      `FROM observation_providers p WHERE p.code = 'ndbc'\n` +
      `ON CONFLICT (provider_id, external_id) DO UPDATE SET name = EXCLUDED.name, latitude = EXCLUDED.latitude, longitude = EXCLUDED.longitude, temperature_available = true, updated_at = now();`
    );
  }
  for (const c of candidates) {
    lines.push(
      `INSERT INTO spot_observation_stations (spot_id, station_id, distance_km, suitability_score, match_type, status)\n` +
      `SELECT ${q(c.spot.id)}, st.id, ${c.distanceKm}, ${c.suitabilityScore}, 'auto_distance', 'candidate'\n` +
      `FROM observation_stations st JOIN observation_providers p ON p.id = st.provider_id AND p.code = 'ndbc'\n` +
      `WHERE st.external_id = ${q(c.station.externalId)}\n` +
      `ON CONFLICT (spot_id, station_id) DO NOTHING;`
    );
  }
  writeFileSync(sqlOut, lines.join('\n\n') + '\n');
  console.log(`\nSeed SQL written to ${sqlOut}`);
}

if (doWrite) {
  const serviceKey = process.env.SUPABASE_SERVICE_KEY;
  if (!serviceKey) { console.error('SUPABASE_SERVICE_KEY not set — cannot --write.'); process.exit(1); }
  const { createClient } = await import('@supabase/supabase-js');
  const { createSupabaseStore } = await import('../api/_lib/observations/ingest.js');
  const sb = createClient(SUPABASE_URL, serviceKey);
  const store = createSupabaseStore(sb);
  const { data: provider } = await sb.from('observation_providers').select('id').eq('code', 'ndbc').single();
  const map = await store.upsertStations(provider.id, wantedStations.map((s) => ({
    externalId: s.externalId, name: s.name, latitude: s.latitude, longitude: s.longitude,
    stationType: s.stationType, waterBody: s.waterBody, sensorDepthM: s.sensorDepthM, metadata: s.metadata || {},
  })));
  const links = candidates.map((c) => ({
    spot_id: c.spot.id,
    station_id: map.get(c.station.externalId),
    distance_km: c.distanceKm,
    suitability_score: c.suitabilityScore,
    match_type: 'auto_distance',
    status: 'candidate',
  })).filter((l) => l.station_id);
  const { error } = await sb.from('spot_observation_stations')
    .upsert(links, { onConflict: 'spot_id,station_id', ignoreDuplicates: true });
  if (error) { console.error('write failed:', error.message); process.exit(1); }
  console.log(`\nWrote ${wantedStations.length} stations and ${links.length} candidate links.`);
}
